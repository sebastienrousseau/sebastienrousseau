#!/usr/bin/env bash
# Commit through GitHub's createCommitOnBranch API, so every commit is
# signed by GitHub and shows as Verified.
#
#   tools/commit.sh ensure <branch>                 create <branch> as an orphan if missing
#   tools/commit.sh push <dir> <branch> <headline>  commit <dir>'s changes to <branch>
#
# Needs GH_TOKEN with contents: write and GITHUB_REPOSITORY (set in Actions).
set -euo pipefail

ensure() {
  local branch=$1 tree commit
  if gh api "repos/$GITHUB_REPOSITORY/branches/$branch" --silent 2>/dev/null; then
    return
  fi
  tree=$(jq -n '{tree: [{path: "README.md", mode: "100644", type: "blob",
    content: "Generated by tools/live.py on main. Do not edit: every refresh overwrites it.\n"}]}' |
    gh api "repos/$GITHUB_REPOSITORY/git/trees" --input - --jq .sha)
  commit=$(gh api "repos/$GITHUB_REPOSITORY/git/commits" \
    -f message="chore: start the $branch branch" -f "tree=$tree" --jq .sha)
  gh api "repos/$GITHUB_REPOSITORY/git/refs" -f "ref=refs/heads/$branch" -f "sha=$commit" --silent
  echo "Created $branch at $commit."
}

push() {
  local dir=$1 branch=$2 headline=$3
  cd "$dir"
  git add -A
  if git diff --cached --quiet; then
    echo "No changes."
    return
  fi
  work=$(mktemp -d)
  # `work` is global on purpose: the trap fires at shell exit, after this
  # function's locals are gone, and set -u would reject a local there.
  trap 'rm -rf "$work"' EXIT
  # Contents go through files: base64 of a full refresh exceeds the
  # 128 KiB limit on a single argument.
  git diff --cached --no-renames --name-only -z --diff-filter=d |
    while IFS= read -r -d '' path; do
      base64 <"$path" | tr -d '\n' >"$work/blob"
      jq -n --arg p "$path" --rawfile c "$work/blob" '{path: $p, contents: $c}'
    done | jq -s . >"$work/additions"
  git diff --cached --no-renames --name-only -z --diff-filter=D |
    jq -Rs 'split("\u0000") | map(select(length > 0) | {path: .})' >"$work/deletions"
  jq -n \
    --arg repo "$GITHUB_REPOSITORY" \
    --arg branch "$branch" \
    --arg head "$(git rev-parse HEAD)" \
    --arg headline "$headline" \
    --slurpfile additions "$work/additions" \
    --slurpfile deletions "$work/deletions" \
    '{query: "mutation($i: CreateCommitOnBranchInput!) { createCommitOnBranch(input: $i) { commit { url } } }",
      variables: {i: {
        branch: {repositoryNameWithOwner: $repo, branchName: $branch},
        expectedHeadOid: $head,
        message: {headline: $headline},
        fileChanges: {additions: $additions[0], deletions: $deletions[0]}}}}' |
    gh api graphql --input - --jq .data.createCommitOnBranch.commit.url
}

case ${1:-} in
  ensure) ensure "$2" ;;
  push) push "$2" "$3" "$4" ;;
  *)
    echo "usage: $0 ensure <branch> | push <dir> <branch> <headline>" >&2
    exit 2
    ;;
esac
