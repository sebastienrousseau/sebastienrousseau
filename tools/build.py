"""Render the static assets/*.svg and README.md from profile.toml.

make            # or: uv run --no-project --with fonttools==... tools/build.py

The panels that change (numbers, latest articles, project cards with their
stars and downloads) are not drawn here:
tools/live.py renders them onto the profile-data branch, and the README
points there. This build needs no network beyond the pinned fonts, and its
output is a pure function of profile.toml and tools/, so CI checks that
the committed files match it.
"""

from __future__ import annotations

import html
import tomllib
from collections.abc import Callable
from pathlib import Path

import articles
import panels
from svg import Doc

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "assets"
NUMBERS_ALT = (
    "By the numbers: all-time downloads, downloads in the last 30 days, GitHub stars and packages"
    " published, live from crates.io, PyPI, npm and GitHub."
)


def jobs(cfg: dict) -> dict[str, Callable[[dict], Doc]]:
    """Every static asset name mapped to the panel that draws it for a theme."""
    out: dict[str, Callable[[dict], Doc]] = {
        "hero": lambda t: panels.hero(t, cfg["hero"]),
        "paper": lambda t: panels.paper(t, cfg["paper"]),
        "desk": lambda t: panels.header(t, "Latest", "From the desk."),
        "finale": lambda t: panels.finale(t, cfg["finale"]),
    }
    for n, p in enumerate(cfg["pillars"], 1):
        out[f"section-{p['key']}"] = lambda t, p=p, n=n: panels.section(t, p, n)
    return out


def pic(name: str, alt: str, url: str | None = None, width: str = "100%", base: str = "assets") -> str:
    img = (
        f'<picture><source media="(prefers-color-scheme: dark)" srcset="{base}/{name}-dark.svg">'
        f'<img src="{base}/{name}-light.svg" width="{width}" alt="{html.escape(alt)}"></picture>'
    )
    return f'<a href="{html.escape(url)}">{img}</a>' if url else img


def page(cfg: dict, alts: dict[str, str]) -> str:
    gh, site, live = cfg["github"], cfg["site"], cfg["live"]
    links = " &nbsp;·&nbsp; ".join(
        f'<a href="{html.escape(x["url"])}">{html.escape(x["label"])}</a>' for x in cfg["finale"]["links"]
    )
    out = [
        "<!-- Generated by tools/build.py from profile.toml. Edit those, not this file. -->",
        # The hero is served live by the profile-clock Worker, which sets the
        # clock to London time; the committed assets/hero-*.svg are its source
        # and the static fallback it redirects to.
        pic("hero", alts["hero"], site, base=cfg.get("clock", "assets")),
        f'<p align="center">{links}</p>',
        # Numbers and articles live on the profile-data branch, refreshed by
        # .github/workflows/refresh.yml without touching main.
        pic("numbers", NUMBERS_ALT, base=live),
    ]
    for p in cfg["pillars"]:
        cards = [pic(f"card-{r['name']}", panels.card_alt(r), f"{gh}/{r['name']}", "49%", live) for r in p["repos"]]
        out += [
            pic(f"section-{p['key']}", alts[f"section-{p['key']}"]),
            "<p>\n" + "\n".join(cards) + "\n</p>",
            f'<p align="right"><a href="{html.escape(p["more"])}">Learn more about {p["eyebrow"]} ›</a></p>',
        ]
    index = f"{site}/articles/"
    desk = [
        pic(f"article-{n}", f"Latest article {n} from sebastienrousseau.com.", index, "32.6%", live)
        for n in range(1, articles.COUNT + 1)
    ]
    out += [
        pic("paper", alts["paper"], cfg["paper"]["url"]),
        pic("desk", alts["desk"]),
        "<p>\n" + "\n".join(desk) + "\n</p>",
        f'<p align="right"><a href="{index}">See all articles ›</a></p>',
        pic("finale", alts["finale"], f"{site}/contact/"),
        f'<p align="center"><sub>Built from <a href="profile.toml">profile.toml</a> in the typefaces'
        f' and colours of <a href="{site}">sebastienrousseau.com</a>.</sub></p>',
    ]
    return "\n\n".join(out) + "\n"


def main() -> None:
    cfg = tomllib.loads((ROOT / "profile.toml").read_text())
    alts = panels.write(jobs(cfg), ASSETS)
    (ROOT / "README.md").write_text(page(cfg, alts))


if __name__ == "__main__":
    main()
